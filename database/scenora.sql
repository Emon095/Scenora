create table if not exists public.notifications (
  id uuid primary key default gen_random_uuid(),
  recipient_id uuid not null references public.users(id) on delete cascade,
  actor_id uuid references public.users(id) on delete cascade,
  type text not null check (type in ('like', 'comment', 'follow', 'mention', 'rating')),
  entity_id uuid,
  read boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.shoutbox_messages (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.users(id) on delete cascade,
  type text not null default 'text' check (type in ('text', 'image', 'voice')),
  body text check (body is null or char_length(body) <= 2000),
  media_url text,
  duration integer check (duration is null or duration between 0 and 600),
  created_at timestamptz not null default now(),
  check (body is not null or media_url is not null)
);

create table if not exists public.shoutbox_reactions (
  message_id uuid not null references public.shoutbox_messages(id) on delete cascade,
