create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = '' as $$
declare
  requested_username text;
begin
  requested_username := lower(regexp_replace(coalesce(new.raw_user_meta_data ->> 'username', split_part(new.email, '@', 1)), '[^a-zA-Z0-9_]', '', 'g'));
  if char_length(requested_username) < 3 then requested_username := 'user_' || substr(new.id::text, 1, 8); end if;
  insert into public.users (id, email, username)
  values (new.id, coalesce(new.email, ''), requested_username)
  on conflict (id) do nothing;
  insert into public.profiles (user_id, display_name)
  values (new.id, coalesce(new.raw_user_meta_data ->> 'full_name', requested_username))
  on conflict (user_id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute function public.handle_new_user();

create or replace function public.create_social_notification()
returns trigger language plpgsql security definer set search_path = '' as $$
declare target_user uuid;
declare notification_type text;
declare target_entity uuid;
declare actor_user uuid;
begin
  if tg_table_name = 'post_likes' then
    select author_id into target_user from public.posts where id = new.post_id;
    notification_type := 'like'; target_entity := new.post_id; actor_user := new.user_id;
  elsif tg_table_name = 'post_comments' then
    select author_id into target_user from public.posts where id = new.post_id;
    notification_type := 'comment'; target_entity := new.post_id; actor_user := new.user_id;
  elsif tg_table_name = 'follows' then
    target_user := new.following_id; notification_type := 'follow'; target_entity := new.follower_id; actor_user := new.follower_id;
  elsif tg_table_name = 'reviews' then
    select author_id into target_user from public.posts where id = new.post_id;
    notification_type := 'rating'; target_entity := new.post_id; actor_user := new.user_id;
  end if;
  if target_user is not null and target_user <> actor_user then
    insert into public.notifications(recipient_id, actor_id, type, entity_id)
    values (target_user, actor_user, notification_type, target_entity);
  end if;
  return new;
end;
$$;

